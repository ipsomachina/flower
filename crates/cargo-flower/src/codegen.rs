//! Deterministic TypeScript application contracts from the validated manifest.
use flower_engine::descriptors::{DefKind, ModuleDef};
use flower_sdk::schema::Schema;

fn quoted(value: &str) -> String {
    serde_json::to_string(value).expect("string serializes")
}

fn ty(schema: Schema) -> String {
    match schema {
        Schema::DecimalI64 | Schema::DecimalU64 | Schema::String { .. } => "string".into(),
        Schema::Number { .. } | Schema::Int { .. } => "number".into(),
        Schema::Boolean => "boolean".into(),
        Schema::Null => "null".into(),
        Schema::Json => "Json".into(),
        Schema::Array { element } => format!("Array<{}>", ty(*element)),
        Schema::Tuple { elements } => format!(
            "[{}]",
            elements
                .iter()
                .map(|s| ty(*s))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Schema::Nullable { inner } => format!("({} | null)", ty(*inner)),
        Schema::Enum { variants } => {
            if variants.is_empty() {
                "never".into()
            } else {
                variants
                    .iter()
                    .map(|s| quoted(s))
                    .collect::<Vec<_>>()
                    .join(" | ")
            }
        }
        Schema::Object { fields } => format!(
            "{{ {} }}",
            fields
                .iter()
                .map(|f| format!(
                    "{}{}: {};",
                    quoted(f.name),
                    if f.optional { "?" } else { "" },
                    ty(f.schema)
                ))
                .collect::<Vec<_>>()
                .join(" ")
        ),
    }
}

pub fn typescript(module: &ModuleDef) -> String {
    let mut output = String::from(
        "// Generated by cargo flower contract typescript. Do not edit.\n// Static wire types; server validation enforces bounds, patterns and exact decimals.\nexport type Json = null | boolean | number | string | Json[] | { [key: string]: Json };\n",
    );
    for (label, kind) in [
        ("Queries", DefKind::Query),
        ("Mutations", DefKind::Mutation),
    ] {
        output.push_str(&format!("export interface {label} {{\n"));
        for (alias, name) in &module.http {
            if module.def_kinds.get(name) != Some(&kind) {
                continue;
            }
            let args = module.args.get(name).copied().unwrap_or(Schema::Json);
            let result = module.results.get(name).copied().unwrap_or(Schema::Json);
            let errors = module.errors.get(name).copied().unwrap_or(Schema::Json);
            output.push_str(&format!(
                "  {}: {{ args: {}; result: {}; errors: {} }};\n",
                quoted(alias),
                ty(args),
                ty(result),
                ty(errors)
            ));
        }
        output.push_str("}\n");
    }
    output
}

pub fn validate_call(
    module: &ModuleDef,
    alias: &str,
    mutation: bool,
    args: &serde_json::Value,
) -> Result<(), String> {
    let name = module
        .http
        .get(alias)
        .ok_or_else(|| format!("no public method named {alias}"))?;
    let expected = if mutation {
        DefKind::Mutation
    } else {
        DefKind::Query
    };
    if module.def_kinds.get(name) != Some(&expected) {
        return Err(format!("{alias} is not a {expected:?}"));
    }
    let schema = module
        .args
        .get(name)
        .ok_or_else(|| format!("{alias} has no argument contract"))?;
    let bytes = serde_json::to_vec(args).map_err(|e| e.to_string())?;
    let value = flower_engine::json::parse_value(&bytes).map_err(|e| e.to_string())?;
    schema
        .parse(&value)
        .map_err(|e| format!("{alias}: {}: {}", e.path, e.message))
}

#[cfg(test)]
mod tests {
    use super::*;
    use flower_sdk::schema::{Field, v};
    #[test]
    fn preserves_omission_null_exact_integer_and_escaped_names() {
        let schema = Schema::Object {
            fields: &[Field {
                name: "a\"b",
                optional: true,
                schema: Schema::Nullable {
                    inner: &Schema::DecimalI64,
                },
            }],
        };
        assert_eq!(ty(schema), "{ \"a\\\"b\"?: (string | null); }");
        assert_eq!(ty(v::boolean()), "boolean");
    }
    #[test]
    fn exports_only_public_aliases_and_validates_kind_before_delivery() {
        let mut module = ModuleDef::default();
        module.http.insert("public-name".into(), "internal".into());
        module.def_kinds.insert("internal".into(), DefKind::Query);
        module.args.insert("internal".into(), Schema::DecimalI64);
        let generated = typescript(&module);
        assert!(generated.contains("\"public-name\": { args: string"));
        assert!(!generated.contains("internal"));
        assert!(
            validate_call(
                &module,
                "public-name",
                false,
                &serde_json::json!("9223372036854775807")
            )
            .is_ok()
        );
        assert!(validate_call(&module, "public-name", false, &serde_json::json!(42)).is_err());
        assert!(validate_call(&module, "public-name", true, &serde_json::json!("1")).is_err());
        assert!(validate_call(&module, "internal", false, &serde_json::json!("1")).is_err());
    }
}
