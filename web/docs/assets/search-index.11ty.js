import { PAGES, readContent, fillIncludes, addIds, searchEntries } from "../../_lib/docs.mjs";

export function data() {
  return {
    layout: false,
    permalink: "/docs/assets/search-index.js",
    buildawesomeExcludeFromCollections: true,
  };
}

export default function() {
  const search = PAGES.flatMap(page => {
    const { html } = addIds(fillIncludes(page, readContent(page)));
    return searchEntries(page, html);
  });
  return "// Generated by Build Awesome from the documentation. Do not edit.\n" +
    `window.FLOWER_SEARCH = ${JSON.stringify(search)};\n`;
}
